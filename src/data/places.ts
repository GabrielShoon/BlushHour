function hash(s: string) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
  return h;
}

const COST: Record<PriceLevel, number> = { 0: 0, 1: 15, 2: 40, 3: 85, 4: 180 };

interface Input {
  name: string;
  slug?: string;
  kind?: Kind;
  category: CategoryId;
  area: string;
  coordArea?: string | null;
  price: PriceLevel;
  cost?: number;
  mins: number;
  blurb: string;
  note?: string;
  cuisine?: string;
  vibes: Vibe[];
  time?: TimeOfDay;
  indoor?: boolean;
  branches?: string[];
  status?: "open" | "closed";
  source?: Place["source"];
  unverified?: boolean;
}

const FOOD: CategoryId[] = ["dining", "bars", "cafes", "desserts", "supper"];

function place(i: Input): Place {
  const slug =
    i.slug ??
    i.name
      .toLowerCase()
      .replace(/&/g, "and")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "");
  const key = i.coordArea === undefined ? i.area : i.coordArea;
  const base = key ? AREAS[key] : null;
  if (key && !base) throw new Error(`Unknown area for ${i.name}: ${key}`);
  const h = hash(slug);
  return {
    slug,
    name: i.name,
    kind: i.kind ?? (FOOD.includes(i.category) ? "food" : "activity"),
    category: i.category,
    area: i.area,
    lat: base ? +(base[0] + ((h % 100) / 100) * 0.003 - 0.0015).toFixed(5) : null,
    lng: base ? +(base[1] + (((h >> 8) % 100) / 100) * 0.003 - 0.0015).toFixed(5) : null,
    priceLevel: i.price,
    costPerPerson: i.cost ?? COST[i.price],
    durationMins: i.mins,
    blurb: i.blurb,
    note: i.note,
    cuisine: i.cuisine,
    vibes: i.vibes,
    timeOfDay: i.time ?? "any",
    indoor: i.indoor ?? true,
    branches: i.branches,
    status: i.status ?? "open",
    source: i.source ?? "curator",
    unverified: i.unverified,
  };
}

